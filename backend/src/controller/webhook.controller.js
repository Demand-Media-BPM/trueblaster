const crypto = require("crypto");
const axios = require("axios");
const { HttpError, asyncHandler } = require("../middleware/request");
const CampaignRecipient = require("../models/campaignRecipient.model");
const CampaignEvent = require("../models/campaignEvent.model");
const Suppression = require("../models/suppression.model");
const certificates = new Map();

function signingString(message) {
  const fields =
    message.Type === "Notification"
      ? [
        "Message",
        "MessageId",
        ...(message.Subject !== undefined ? ["Subject"] : []),
        "Timestamp",
        "TopicArn",
        "Type",
      ]
      : ["Message", "MessageId", "SubscribeURL", "Timestamp", "Token", "TopicArn", "Type"];
  if (fields.some((k) => typeof message[k] !== "string"))
    throw new HttpError(400, "Invalid SNS message fields");
  return fields.map((k) => `${k}\n${message[k]}\n`).join("");
}

function snsHost(message) {
  const allowed = (process.env.SES_SNS_TOPIC_ARNS || "")
    .split(",")
    .map((s) => s.trim())
    .filter(Boolean);
  if (!allowed.length) throw new HttpError(503, "SES_SNS_TOPIC_ARNS must be configured");
  if (!allowed.includes(message.TopicArn)) throw new HttpError(403, "SNS topic is not allowed");
  const arn = /^arn:(aws|aws-cn):sns:([a-z0-9-]+):\d{12}:[A-Za-z0-9_-]+$/.exec(message.TopicArn);
  if (!arn) throw new HttpError(403, "Invalid SNS topic");
  return `sns.${arn[2]}.amazonaws.com${arn[1] === "aws-cn" ? ".cn" : ""}`;
}

// Verify the SNS signature and approved topic before trusting a delivery notification.
async function verifyMessage(message) {
  if (
    !["Notification", "SubscriptionConfirmation", "UnsubscribeConfirmation"].includes(message.Type)
  )
    throw new HttpError(400, "Unsupported SNS message type");
  const host = snsHost(message);
  let url;
  try {
    url = new URL(message.SigningCertURL);
  } catch {
    throw new HttpError(403, "Invalid SNS certificate URL");
  }
  if (
    url.protocol !== "https:" ||
    url.hostname !== host ||
    url.port ||
    url.username ||
    url.password ||
    url.search ||
    !/^\/SimpleNotificationService-[A-Za-z0-9]+\.pem$/.test(url.pathname)
  )
    throw new HttpError(403, "Invalid SNS certificate URL");
  const algorithm = { 1: "RSA-SHA1", 2: "RSA-SHA256" }[message.SignatureVersion];
  if (!algorithm) throw new HttpError(403, "Invalid SNS signature version");
  let cached = certificates.get(url.href);
  if (!cached || cached.expires < Date.now()) {
    const result = await axios.get(url.href, {
      timeout: 5000,
      maxRedirects: 0,
      responseType: "text",
      maxContentLength: 20000,
    });
    const cert = new crypto.X509Certificate(result.data);
    if (new Date(cert.validFrom) > new Date() || new Date(cert.validTo) < new Date())
      throw new HttpError(403, "Expired SNS certificate");
    cached = {
      key: cert.publicKey,
      expires: Math.min(new Date(cert.validTo).getTime(), Date.now() + 3600000),
    };
    if (certificates.size >= 32) certificates.clear();
    certificates.set(url.href, cached);
  }
  if (
    !crypto.verify(
      algorithm,
      Buffer.from(signingString(message)),
      cached.key,
      Buffer.from(message.Signature || "", "base64")
    )
  )
    throw new HttpError(403, "Invalid SNS signature");
  return host;
}

async function handleMessage(message) {
  const host = await verifyMessage(message);
  if (message.Type === "SubscriptionConfirmation") {
    const url = new URL(message.SubscribeURL);
    if (
      url.protocol !== "https:" ||
      url.hostname !== host ||
      url.port ||
      url.username ||
      url.password ||
      url.searchParams.get("Action") !== "ConfirmSubscription" ||
      url.searchParams.get("TopicArn") !== message.TopicArn ||
      url.searchParams.get("Token") !== message.Token
    )
      throw new HttpError(403, "Invalid subscription URL");
    await axios.get(url.href, { timeout: 5000, maxRedirects: 0 });
    return;
  }
  if (message.Type !== "Notification") return;
  return applyNotification(message);
}

async function applyNotification(message) {
  const payload = JSON.parse(message.Message);
  const type = payload.notificationType || payload.eventType;
  const action = { Delivery: "delivery", Bounce: "bounce", Complaint: "complaint" }[type];
  if (!action || !payload.mail?.messageId) return;
  // Message IDs are generated by SES. Never accept workspace IDs from a public request body.
  const recipients = await CampaignRecipient.find({ messageId: payload.mail.messageId });
  for (const recipient of recipients) {
    const scope = {
      workspaceId: recipient.workspaceId,
      campaignId: recipient.campaignId,
      recipientId: recipient._id,
    };
    const eventEmails =
      action === "bounce"
        ? payload.bounce?.bouncedRecipients?.map((r) => r.emailAddress.toLowerCase())
        : action === "complaint"
          ? payload.complaint?.complainedRecipients?.map((r) => r.emailAddress.toLowerCase())
          : payload.delivery?.recipients?.map((e) => e.toLowerCase());
    if (eventEmails?.length && !eventEmails.includes(recipient.email)) continue;
    const dedupeKey = `sns:${message.MessageId}:${recipient._id}:${action}`;
    await CampaignEvent.updateOne(
      { workspaceId: recipient.workspaceId, dedupeKey },
      {
        $setOnInsert: {
          ...scope,
          type: action,
          occurredAt: new Date(payload.mail.timestamp || Date.now()),
        },
      },
      { upsert: true }
    );
    const filter = {
      _id: recipient._id,
      workspaceId: recipient.workspaceId,
      campaignId: recipient.campaignId,
    };
    if (action === "delivery") {
      await CampaignRecipient.updateOne(
        { ...filter, status: { $nin: ["bounced"] } },
        { $set: { status: "delivered", bounceStatus: "no" } }
      );
    } else {
      const reason =
        action === "complaint"
          ? "complaint"
          : payload.bounce?.bounceType === "Permanent"
            ? "hard_bounce"
            : null;
      await CampaignRecipient.updateOne(filter, {
        $set: {
          status: "bounced",
          bounceStatus: action === "complaint" || reason ? "hard" : "soft",
        },
      });
      if (reason)
        await Suppression.updateOne(
          { workspaceId: recipient.workspaceId, email: recipient.email, reason },
          {
            $setOnInsert: {
              workspaceId: recipient.workspaceId,
              email: recipient.email,
              reason,
              campaignId: recipient.campaignId,
            },
          },
          { upsert: true }
        );
    }
  }
  // A notification can arrive before send-result persistence. Ask SNS to retry instead of dropping it.
  if (!recipients.length)
    throw new HttpError(503, "Message mapping not available yet; retry notification");
}

// Accept SNS callbacks only after signature and topic verification.
async function handleSesWebhook(req, res) {
  let message = req.body;
  if (typeof message === "string") {
    try {
      message = JSON.parse(message);
    } catch {
      throw new HttpError(400, "Invalid JSON");
    }
  }
  await handleMessage(message || {});
  res.send("OK");
}

module.exports = { signingString, verifyMessage, handleMessage, applyNotification, handleSesWebhook: asyncHandler(handleSesWebhook) };
